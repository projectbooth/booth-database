// writeFixture is a workspace whose owner's "migration" created the input tables, plus things
// that must never become writable.
const writeFixture = `
CREATE SCHEMA finance_input;
CREATE TABLE finance_input.transactions (
  id bigserial PRIMARY KEY, amount numeric NOT NULL, note text, entered_by text, secret text);
CREATE TABLE finance_input.accounts (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text);
CREATE TABLE finance_input.other (v int);
INSERT INTO finance_input.other VALUES (1);
CREATE SCHEMA reporting;
CREATE TABLE reporting.gold (v int);
CREATE TABLE public.schema_migrations (version bigint);
CREATE VIEW finance_input.v AS SELECT 1 AS one;
CREATE TABLE public.parted (k int) PARTITION BY RANGE (k);
CREATE TABLE public.parted_1 PARTITION OF public.parted FOR VALUES FROM (0) TO (10);
CREATE TABLE public.gen (a int, b int GENERATED ALWAYS AS (a * 2) STORED, c int GENERATED ALWAYS AS IDENTITY);`

func financeScope(grant string) WriteScope {
	return WriteScope{Grant: grant, Tables: []WriteTable{
		{Schema: "finance_input", Name: "transactions", Operations: []string{"insert", "update"}, Columns: []string{"amount", "note", "entered_by"}},
		{Schema: "finance_input", Name: "accounts", Operations: []string{"insert", "delete"}, Columns: []string{"name"}},
	}}
}

func newWriteProvisioner(t *testing.T, now func() time.Time) *Provisioner {
	t.Helper()
	deny, err := tables.CompileIgnore(tables.DefaultIgnore)
	if err != nil {
		t.Fatal(err)
	}
	p, err := New(context.Background(), adminDSN(t), Options{WriteDeny: deny, Now: now})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(p.Close)
	if err := p.RestrictMaintenanceAccess(context.Background()); err != nil {
		t.Fatal(err)
	}
	return p
}

func writeWorkspace(t *testing.T, p *Provisioner) string {
	t.Helper()
	ws := uniqueWorkspace("write")
	exec(t, mustConnect(t, issue(t, p, ws, true, time.Minute)), writeFixture)
	return ws
}

func issueWrite(t *testing.T, p *Provisioner, ws string, scope WriteScope, ttl time.Duration) (Lease, []GrantedTable) {
	t.Helper()
	l, g, err := p.IssueWrite(context.Background(), ws, uuid.NewString(), scope, ttl, WriteAudit{Subject: "apiwrite:test", OnBehalfOf: "app:test"})
	if err != nil {
		t.Fatalf("IssueWrite: %v", err)
	}
	return l, g
}

// wantState runs stmt and requires the given SQLSTATE ("" for success).
func wantState(t *testing.T, c *pgx.Conn, want, stmt string) {
	t.Helper()
	_, err := c.Exec(context.Background(), stmt)
	if got := sqlState(err); got != want || (want == "" && err != nil) {
		t.Errorf("%s: got %q (%v), want %q", stmt, got, err, want)
	}
}

func TestWrite_LeaseDoesOnlyWhatWasGranted(t *testing.T) {
	p := newWriteProvisioner(t, nil)
	ws := writeWorkspace(t, p)
	n, _ := naming.ForWorkspace(ws)
	l, granted := issueWrite(t, p, ws, financeScope("api:finance"), time.Minute)

	if len(granted) != 2 || granted[0].Name != "transactions" || !slices.Equal(granted[0].Operations, []string{"insert", "update"}) ||
		!slices.Equal(granted[0].Sequences, []string{`"finance_input"."transactions_id_seq"`}) ||
		!slices.Equal(granted[1].Operations, []string{"delete", "insert"}) || len(granted[1].Sequences) != 1 {
		t.Fatalf("granted: %+v", granted)
	}

	c := mustConnect(t, l)
	var setting string
	if err := c.QueryRow(context.Background(), "SHOW lock_timeout").Scan(&setting); err != nil || setting != "5s" {
		t.Errorf("lock_timeout = %q %v", setting, err)
	}

	// What it may do: the declared operations, on the declared columns, with RETURNING and the
	// tables' own sequences (serial and identity).
	for _, ok := range []string{
		"INSERT INTO finance_input.transactions (amount, note, entered_by) VALUES (12.5, 'coffee', 'sam') RETURNING id",
		"UPDATE finance_input.transactions SET note = 'tea' WHERE id = 1 RETURNING id, amount",
		"SELECT * FROM finance_input.transactions",
		"INSERT INTO finance_input.accounts (name) VALUES ('chequing') RETURNING id",
		"DELETE FROM finance_input.accounts WHERE name = 'chequing'",
		"INSERT INTO finance_input.transactions (amount) VALUES (1) ON CONFLICT (id) DO NOTHING",
	} {
		wantState(t, c, "", ok)
	}

	// Everything else is refused by PostgreSQL itself.
	for _, stmt := range []string{
		"UPDATE finance_input.transactions SET secret = 'x'",                      // undeclared column
		"INSERT INTO finance_input.transactions (amount, secret) VALUES (1, 'x')", // undeclared column
		"DELETE FROM finance_input.transactions",                                  // delete not declared here
		"UPDATE finance_input.accounts SET name = 'x'",                            // update not declared here
		"SELECT * FROM finance_input.other",                                       // undeclared table, same schema
		"INSERT INTO finance_input.other VALUES (2)",
		"DELETE FROM finance_input.other",
		"SELECT * FROM finance_input.v", // a view in the same schema
		"SELECT * FROM reporting.gold",  // another schema
		"INSERT INTO reporting.gold VALUES (1)",
		"SELECT * FROM public.schema_migrations",
		"TRUNCATE finance_input.transactions",
		"TRUNCATE finance_input.accounts",
		"CREATE TABLE finance_input.new_table (v int)",
		"CREATE TABLE public.new_table (v int)",
		"CREATE SCHEMA mine",
		"ALTER TABLE finance_input.transactions ADD COLUMN z int",
		"CREATE INDEX ON finance_input.transactions (note)",
		"DROP TABLE finance_input.transactions",
		"COMMENT ON TABLE finance_input.transactions IS 'x'",
		"GRANT SELECT ON finance_input.other TO PUBLIC",
		"CREATE TEMP TABLE scratch (v int)",
		"SET ROLE " + n.ReadWrite,
		"SET ROLE " + n.ReadOnly,
	} {
		_, err := c.Exec(context.Background(), stmt)
		if s := sqlState(err); s != "42501" {
			t.Errorf("%s: got %q (%v), want 42501", stmt, s, err)
		}
	}

	// Without its group, the bare lease role can do nothing at all.
	exec(t, c, "SET ROLE NONE")
	wantState(t, c, "42501", "SELECT * FROM finance_input.transactions")
	exec(t, c, "RESET ROLE")

	// Other databases: another workspace's, and the maintenance database.
	other := uniqueWorkspace("write-other")
	issue(t, p, other, false, time.Minute)
	on, _ := naming.ForWorkspace(other)
	for _, db := range []string{on.Database, "postgres"} {
		if conn, err := connectAs(t, l, db); err == nil {
			conn.Close(context.Background())
			t.Errorf("write lease connected to %s", db)
		}
	}
}

// "Cannot read what _ro cannot": across every relation in the workspace database (the system
// catalogs included), the write group's SELECT is a subset of the read-only group's.
func TestWrite_ReadsNoMoreThanReadOnly(t *testing.T) {
	p := newWriteProvisioner(t, nil)
	ws := writeWorkspace(t, p)
	n, _ := naming.ForWorkspace(ws)
	issueWrite(t, p, ws, financeScope("api:finance"), time.Minute)
	group := n.WriteGroup("api:finance")

	err := p.inDatabase(context.Background(), n.Database, func(c *pgx.Conn) error {
		rows, err := c.Query(context.Background(), `
			SELECT format('%I.%I', ns.nspname, c.relname)
			  FROM pg_class c JOIN pg_namespace ns ON ns.oid = c.relnamespace
			 WHERE c.relkind IN ('r', 'p', 'v', 'm', 'S', 'f')
			   AND has_table_privilege($1, c.oid, 'SELECT') AND NOT has_table_privilege($2, c.oid, 'SELECT')`,
			group, n.ReadOnly)
		if err != nil {
			return err
		}
		extra, err := pgx.CollectRows(rows, pgx.RowTo[string])
		if err != nil {
			return err
		}
		if len(extra) > 0 {
			t.Errorf("the write group can read what _ro cannot: %v", extra)
		}
		var total int
		if err := c.QueryRow(context.Background(), `
			SELECT count(*) FROM pg_class c JOIN pg_namespace ns ON ns.oid = c.relnamespace
			 WHERE ns.nspname NOT LIKE 'pg\_%' AND ns.nspname <> 'information_schema'
			   AND has_table_privilege($1, c.oid, 'SELECT')`, group).Scan(&total); err != nil {
			return err
		}
		if total != 2 {
			t.Errorf("the write group can read %d user relations, want exactly the 2 declared", total)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

// Each verification rule refuses with a ScopeError naming the table, and a refused issuance
// changes nothing: an earlier lease of the same grant keeps exactly what it had.
func TestWrite_VerificationRefusals(t *testing.T) {
	p := newWriteProvisioner(t, nil)
	ws := writeWorkspace(t, p)
	n, _ := naming.ForWorkspace(ws)
	// A table the workspace's _rw does not own (made by the admin directly).
	if err := p.inDatabase(context.Background(), n.Database, func(c *pgx.Conn) error {
		_, err := c.Exec(context.Background(), "CREATE TABLE public.admin_owned (v int)")
		return err
	}); err != nil {
		t.Fatal(err)
	}
	l, _ := issueWrite(t, p, ws, financeScope("api:finance"), time.Minute)
	c := mustConnect(t, l)

	tbl := func(schema, name string, ops []string, cols ...string) WriteScope {
		return WriteScope{Grant: "api:finance", Tables: []WriteTable{{Schema: schema, Name: name, Operations: ops, Columns: cols}}}
	}
	ins := []string{"insert"}
	for _, c := range []struct {
		scope WriteScope
		want  string
	}{
		{tbl("finance_input", "missing", ins, "v"), "does not exist"},
		{tbl("finance_input", "v", ins, "one"), "is not a table"},
		{tbl("public", "parted_1", ins, "k"), "is a partition"},
		{tbl("pg_catalog", "pg_class", ins, "relname"), "system schema"},
		{tbl("information_schema", "sql_features", ins, "feature_id"), "system schema"},
		{tbl("booth_database", "workspaces", ins, "slug"), "system schema"},
		{tbl("public", "schema_migrations", ins, "version"), "tableEvents.ignore"},
		{tbl("app", "schema_migrations", ins, "version"), "tableEvents.ignore"},
		{tbl("public", "admin_owned", ins, "v"), "not owned by the workspace"},
		{tbl("finance_input", "transactions", ins, "nope"), `has no column "nope"`},
		{tbl("public", "gen", ins, "b"), "is generated"},
		{tbl("public", "gen", ins, "c"), "GENERATED ALWAYS AS IDENTITY"},
		// One bad table refuses the whole grant.
		{WriteScope{Grant: "api:finance", Tables: append(financeScope("x").Tables, WriteTable{Schema: "reporting", Name: "nope", Operations: ins, Columns: []string{"v"}})}, `"reporting"."nope" does not exist`},
	} {
		_, _, err := p.IssueWrite(context.Background(), ws, uuid.NewString(), c.scope, time.Minute, WriteAudit{})
		var se *ScopeError
		if !errors.As(err, &se) || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%+v: err = %v, want a ScopeError containing %q", c.scope.Tables, err, c.want)
		}
	}
	// The partitioned parent itself is fine.
	if _, _, err := p.IssueWrite(context.Background(), ws, uuid.NewString(), tbl("public", "parted", ins, "k"), time.Minute, WriteAudit{}); err != nil {
		t.Errorf("partitioned table refused: %v", err)
	}
	// ...and that issuance reset the group to it: the earlier lease now writes there, not to
	// transactions (shown below). Restore the finance grant and check the refusals left it intact.
	issueWrite(t, p, ws, financeScope("api:finance"), time.Minute)
	if _, _, err := p.IssueWrite(context.Background(), ws, uuid.NewString(), tbl("finance_input", "missing", ins, "v"), time.Minute, WriteAudit{}); err == nil {
		t.Fatal("missing table granted")
	}
	wantState(t, c, "", "INSERT INTO finance_input.transactions (amount) VALUES (3)")
	wantState(t, c, "42501", "INSERT INTO public.parted (k) VALUES (1)")
}

func TestValidateWriteScope(t *testing.T) {
	good := financeScope("api:finance")
	if err := ValidateWriteScope(good); err != nil {
		t.Fatal(err)
	}
	mod := func(f func(*WriteScope)) WriteScope {
		s := WriteScope{Grant: good.Grant}
		for _, t := range good.Tables {
			t.Operations = slices.Clone(t.Operations)
			t.Columns = slices.Clone(t.Columns)
			s.Tables = append(s.Tables, t)
		}
		f(&s)
		return s
	}
	many := make([]WriteTable, MaxWriteTables+1)
	for i := range many {
		many[i] = WriteTable{Schema: "s", Name: strings.Repeat("t", i+1), Operations: []string{"delete"}}
	}
	for name, s := range map[string]WriteScope{
		"empty grant":           mod(func(s *WriteScope) { s.Grant = "" }),
		"long grant":            mod(func(s *WriteScope) { s.Grant = strings.Repeat("g", MaxGrantIDLen+1) }),
		"control char in grant": mod(func(s *WriteScope) { s.Grant = "api:\nx" }),
		"no tables":             mod(func(s *WriteScope) { s.Tables = nil }),
		"too many tables":       {Grant: "g", Tables: many},
		"duplicate table":       mod(func(s *WriteScope) { s.Tables = append(s.Tables, s.Tables[0]) }),
		"empty schema":          mod(func(s *WriteScope) { s.Tables[0].Schema = "" }),
		"long name":             mod(func(s *WriteScope) { s.Tables[0].Name = strings.Repeat("n", 64) }),
		"no operations":         mod(func(s *WriteScope) { s.Tables[0].Operations = nil }),
		"unknown operation":     mod(func(s *WriteScope) { s.Tables[0].Operations = []string{"truncate"} }),
		"duplicate operation":   mod(func(s *WriteScope) { s.Tables[0].Operations = []string{"insert", "insert"} }),
		"insert with no column": mod(func(s *WriteScope) { s.Tables[0].Columns = nil }),
		"columns with delete":   mod(func(s *WriteScope) { s.Tables[0].Operations = []string{"delete"} }),
		"duplicate column":      mod(func(s *WriteScope) { s.Tables[0].Columns = []string{"note", "note"} }),
		"NUL in column":         mod(func(s *WriteScope) { s.Tables[0].Columns = []string{"a\x00b"} }),
	} {
		var se *ScopeError
		if err := ValidateWriteScope(s); !errors.As(err, &se) {
			t.Errorf("%s: err = %v, want a ScopeError", name, err)
		}
	}
}

// Narrowing a grant (a reissue with a smaller scope) applies to an already-open session of an
// earlier lease at its next statement, inside an open transaction too; a revoke ends the
// sessions, the leases and the group.
func TestWrite_RevocationBitesOnTheNextStatement(t *testing.T) {
	p := newWriteProvisioner(t, nil)
	ws := writeWorkspace(t, p)
	n, _ := naming.ForWorkspace(ws)
	l, _ := issueWrite(t, p, ws, financeScope("api:finance"), time.Minute)
	c := mustConnect(t, l)
	ctx := context.Background()

	wantState(t, c, "", "INSERT INTO finance_input.transactions (amount) VALUES (1)")
	exec(t, c, "BEGIN")
	wantState(t, c, "", "INSERT INTO finance_input.accounts (name) VALUES ('a')")

	// The owner removes transactions from the declaration; booth-api reissues.
	narrow := financeScope("api:finance")
	narrow.Tables = narrow.Tables[1:]
	issueWrite(t, p, ws, narrow, time.Minute)

	wantState(t, c, "", "INSERT INTO finance_input.accounts (name) VALUES ('b')")
	wantState(t, c, "42501", "INSERT INTO finance_input.transactions (amount) VALUES (2)")
	exec(t, c, "ROLLBACK")
	wantState(t, c, "42501", "SELECT 1 FROM finance_input.transactions")
	wantState(t, c, "", "INSERT INTO finance_input.accounts (name) VALUES ('c')")

	// Writes turned off: the revoke ends the session, the lease and the group.
	db, err := p.RevokeWrite(ctx, ws, "api:finance", WriteAudit{Subject: "apiwrite:test"})
	if err != nil || db != n.Database {
		t.Fatalf("RevokeWrite: %q %v", db, err)
	}
	if _, err := c.Exec(ctx, "INSERT INTO finance_input.accounts (name) VALUES ('d')"); err == nil {
		t.Error("a revoked lease's session still writes")
	}
	if conn, err := connectAs(t, l, l.Database); err == nil {
		conn.Close(ctx)
		t.Error("a revoked lease can still log in")
	}
	for _, role := range []string{l.Username, n.WriteGroup("api:finance")} {
		var exists bool
		if err := p.pool.QueryRow(ctx, "SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = $1)", role).Scan(&exists); err != nil || exists {
			t.Errorf("role %s still exists after revoke (%v)", role, err)
		}
	}
	if acc, err := p.WriteAccess(ctx, ws); err != nil || len(acc) != 0 {
		t.Errorf("write access after revoke: %+v %v", acc, err)
	}
	// Revoking again, or a grant never issued, is not an error.
	if _, err := p.RevokeWrite(ctx, ws, "api:finance", WriteAudit{}); err != nil {
		t.Error(err)
	}
	if _, err := p.RevokeWrite(ctx, uniqueWorkspace("never"), "api:x", WriteAudit{}); err != nil {
		t.Error(err)
	}
}

// The owner's migrations: a dropped and recreated table has no grant until the next issuance;
// an added column is not writable until declared; a GRANT the owner makes to the group by hand
// is wiped by the next issuance.
func TestWrite_MigrationsKeepGrantsCorrect(t *testing.T) {
	p := newWriteProvisioner(t, nil)
	ws := writeWorkspace(t, p)
	n, _ := naming.ForWorkspace(ws)
	group := n.WriteGroup("api:finance")
	owner := mustConnect(t, issue(t, p, ws, true, time.Minute))
	l, _ := issueWrite(t, p, ws, financeScope("api:finance"), time.Minute)
	c := mustConnect(t, l)

	exec(t, owner, `DROP TABLE finance_input.transactions;
		CREATE TABLE finance_input.transactions (id bigserial PRIMARY KEY, amount numeric NOT NULL, note text, entered_by text, secret text)`)
	wantState(t, c, "42501", "INSERT INTO finance_input.transactions (amount) VALUES (1)")
	issueWrite(t, p, ws, financeScope("api:finance"), time.Minute)
	wantState(t, c, "", "INSERT INTO finance_input.transactions (amount) VALUES (1)")

	exec(t, owner, "ALTER TABLE finance_input.transactions ADD COLUMN category text")
	wantState(t, c, "", "SELECT category FROM finance_input.transactions")
	wantState(t, c, "42501", "INSERT INTO finance_input.transactions (amount, category) VALUES (1, 'x')")

	exec(t, owner, "GRANT ALL ON finance_input.transactions, finance_input.other TO "+group)
	wantState(t, c, "", "SELECT * FROM finance_input.other") // the owner's own choice, until...
	issueWrite(t, p, ws, financeScope("api:finance"), time.Minute)
	wantState(t, c, "42501", "SELECT * FROM finance_input.other")
	wantState(t, c, "42501", "TRUNCATE finance_input.transactions")
	wantState(t, c, "42501", "UPDATE finance_input.transactions SET secret = 'x'")
}

// The reaper drops a write group once its last lease has gone and it hasn't been issued for
// WriteGroupIdle, revoking its privileges; until then it keeps it.
func TestWrite_ReaperSweepsIdleGroups(t *testing.T) {
	clock := time.Now()
	p := newWriteProvisioner(t, func() time.Time { return clock })
	ws := writeWorkspace(t, p)
	n, _ := naming.ForWorkspace(ws)
	group := n.WriteGroup("api:finance")
	p.sweepOnly = func(g string) bool { return g == group } // this test's clock runs ahead
	ctx := context.Background()
	issueWrite(t, p, ws, financeScope("api:finance"), time.Second)
	if acc, err := p.WriteAccess(ctx, ws); err != nil || len(acc) != 2 || acc[0].Grant != "api:finance" {
		t.Fatalf("write access: %+v %v", acc, err)
	}
	time.Sleep(1500 * time.Millisecond) // PostgreSQL's own clock decides expiry
	exists := func() bool {
		var ok bool
		if err := p.pool.QueryRow(ctx, "SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = $1)", group).Scan(&ok); err != nil {
			t.Fatal(err)
		}
		return ok
	}
	if _, err := p.Reap(ctx); err != nil {
		t.Fatal(err)
	}
	if !exists() {
		t.Fatal("a group issued moments ago was swept")
	}
	clock = clock.Add(DefaultWriteGroupIdle + time.Minute)
	if _, err := p.Reap(ctx); err != nil {
		t.Fatal(err)
	}
	if exists() {
		t.Fatal("an idle write group with no members survived the sweep")
	}
	if acc, err := p.WriteAccess(ctx, ws); err != nil || len(acc) != 0 {
		t.Errorf("privileges outlived the group: %+v %v", acc, err)
	}
	if ids := p.writeGrantIDs(ctx); ids[group] != "" {
		t.Error("the swept group's record is still there")
	}
}

func TestWriteGroupNaming(t *testing.T) {
	a, _ := naming.ForWorkspace("acme")
	b, _ := naming.ForWorkspace("other")
	g := a.WriteGroup("api:finance")
	if len(g) > 63 || !strings.HasPrefix(g, naming.WriteGroupPrefix) || strings.Contains(g, "acme") || strings.Contains(g, "finance") {
		t.Fatalf("group name %q", g)
	}
	if g == a.WriteGroup("api:other") || g == b.WriteGroup("api:finance") || g != a.WriteGroup("api:finance") {
		t.Error("write group names must be per (database, grant) and stable")
	}
	if naming.DatabaseForWriteGroup(g) != a.Database || naming.DatabaseForGroup(g) != a.Database {
		t.Error("a write group must map back to its database")
	}
	if naming.DatabaseForWriteGroup(a.ReadWrite) != "" || naming.DatabaseForWriteGroup("bdb_w_x") != "" {
		t.Error("non-write-group names must not map")
	}
}
